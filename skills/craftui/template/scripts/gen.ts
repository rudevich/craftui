// Regenerates src/index.ts, package.json "exports" and demo/.generated/props.json from the entity folders
// (craftui.config.json → dirs: src/components, src/pages by default). Self-contained: the craftui tooling
// lives in the global MCP server, so gen reads only the config and spec shapes it needs here.
// README.md of entities is written by the MCP server (the readme action of build, verify and the report step).
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import docgen, { type PropItem } from 'react-docgen-typescript';

// Minimal project settings (the defaults mirror the server's lib.ts): only what gen needs.
const raw = fs.existsSync('craftui.config.json') ? JSON.parse(fs.readFileSync('craftui.config.json', 'utf8')) : {};
const cfg = {
  dirs: { component: 'src/components', page: 'src/pages', ...(raw.dirs ?? {}) },
  pages: { export: true, ...(raw.pages ?? {}) },
};
const COMPONENTS = path.basename(cfg.dirs.component);
const PAGES = path.basename(cfg.dirs.page);
const LIBRARY_KINDS = [COMPONENTS];
const DEMO_KINDS = [COMPONENTS, PAGES];

const listEntities = (kind: string): string[] => {
  const dir = path.join('src', kind);
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .filter((d) => d.isDirectory() && fs.existsSync(path.join(dir, d.name, 'index.ts')))
    .map((d) => d.name)
    .sort();
};

const writeIfChanged = (file: string, content: string) => {
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content) return false;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  return true;
};

// 1. Barrel and package exports (library kinds only).
const components = LIBRARY_KINDS.flatMap((kind) => listEntities(kind).map((name) => ({ kind, name })));
const barrel = [
  `// Generated by \`npm run gen\` from ${cfg.dirs.component}/*/index.ts — do not edit.`,
  ...(components.length ? components.map((c) => `export * from './${c.kind}/${c.name}';`) : ['export {};']),
  '',
].join('\n');
writeIfChanged('src/index.ts', barrel);

const pkg = JSON.parse(fs.readFileSync('package.json', 'utf8'));
const exportsMap: Record<string, string | { types: string; import: string }> = {
  '.': { types: './dist/index.d.ts', import: './dist/index.js' },
  './tokens.css': './dist/tokens.css',
};
for (const c of components) {
  exportsMap[`./${c.name}`] = {
    types: `./dist/${c.kind}/${c.name}/index.d.ts`,
    import: `./dist/${c.kind}/${c.name}/index.js`,
  };
}
// Pages are entries of their own (<pkg>/pages/<Page>), not part of the components' barrel.
if (cfg.pages.export) {
  for (const name of listEntities(PAGES)) {
    exportsMap[`./pages/${name}`] = { types: `./dist/${PAGES}/${name}/index.d.ts`, import: `./dist/${PAGES}/${name}/index.js` };
  }
}
if (JSON.stringify(pkg.exports) !== JSON.stringify(exportsMap)) {
  pkg.exports = exportsMap;
  fs.writeFileSync('package.json', `${JSON.stringify(pkg, null, 2)}\n`);
}

// 2. Metadata for demo pages (props table, showcase, playground controls).
// Own props only, plus props Figma defines even if they are native attributes (disabled on <button>).
const readSpec = (kind: string, name: string): SpecLite | null => {
  const file = path.join('src', kind, name, 'craftlog', 'figma', 'spec.json');
  return fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, 'utf8')) : null;
};
// The part of the server's StateRole gen needs: a state prop maps a value to a flag (disabled, loading…).
const figmaNames = (spec: SpecLite | null) =>
  new Set(
    (spec?.props ?? []).flatMap((p) => [
      p.react,
      ...(p.role === 'state' ? Object.values(p.map ?? {}).map((r) => (r && typeof r === 'object' && 'flag' in r ? r.flag : undefined)) : []),
    ]).filter((n): n is string => Boolean(n)),
  );
const allFigmaNames = new Set(DEMO_KINDS.flatMap((kind) => listEntities(kind).flatMap((name) => [...figmaNames(readSpec(kind, name))])));

const isOwn = (prop: PropItem) => !prop.parent?.fileName.includes('node_modules') && !prop.declarations?.every((d) => d.fileName.includes('node_modules'));

// docgen cache: parsing with react-docgen-typescript is the expensive part, the entity's props only change
// with its sources, its spec or the set of Figma prop names that survive the filter.
const CACHE_VERSION = 1;
const digest = (s: string) => createHash('sha256').update(s).digest('hex').slice(0, 16);
const cacheFile = 'demo/.generated/docgen.cache.json';
const docgenCache = fs.existsSync(cacheFile) ? (JSON.parse(fs.readFileSync(cacheFile, 'utf8')) as Record<string, { key: string; props: unknown }>) : {};
const globalKey = digest(`${CACHE_VERSION}|${[...allFigmaNames].sort().join('|')}`);
const parser = docgen.withCustomConfig('tsconfig.json', {
  savePropValueAsString: true,
  shouldExtractLiteralValuesFromEnum: true,
  shouldRemoveUndefinedFromOptional: true,
  propFilter: (prop) => isOwn(prop) || allFigmaNames.has(prop.name),
});

const SIZE_SCALE = ['xxxl', 'xxl', 'xl', 'l', 'm', 's', 'xs', 'xxs', 'xxxs'];
const literal = (v: string): unknown => {
  try {
    return JSON.parse(v);
  } catch {
    return v;
  }
};
// Sizes read best from large to small, like Figma; other unions keep their declaration order.
const orderOptions = (values: unknown[]) =>
  values.every((v) => SIZE_SCALE.includes(v as string)) ? [...values].sort((a, b) => SIZE_SCALE.indexOf(a as string) - SIZE_SCALE.indexOf(b as string)) : values;

// react-docgen-typescript reads defaults from a destructured parameter only; long components destructure `props` in the body.
const sourceDefaults = (source: string) => {
  const block = source.match(/const\s*\{([\s\S]*?)\}\s*=\s*props\s*;/)?.[1] ?? source.match(/function\s+\w+\s*\(\s*\{([\s\S]*?)\}\s*:/)?.[1] ?? '';
  const out: Record<string, string> = {};
  for (const [, key, value] of block.matchAll(/(\w+)\s*=\s*('[^']*'|"[^"]*"|true|false|-?\d+(?:\.\d+)?|null)\s*(?=,|\n|$)/g)) out[key] = value.replace(/^['"]|['"]$/g, '');
  return out;
};
// JSDoc over `export type <Name>Props`: where the other attributes and ref go when not to the root (a field with an <input> inside).
const propsNote = (kind: string, name: string) => {
  const file = path.join('src', kind, name, 'types.ts');
  const doc = fs.existsSync(file) ? fs.readFileSync(file, 'utf8').match(/\/\*\*([\s\S]*?)\*\/\s*export type \w+Props\b/)?.[1] : null;
  return doc ? doc.replace(/^\s*\*\s?/gm, '').replace(/\s+/g, ' ').trim() : undefined;
};

const props: Record<string, unknown> = {};
let parsed = 0;
let fromCache = 0;
for (const kind of DEMO_KINDS) {
  for (const name of listEntities(kind)) {
    const file = path.join('src', kind, name, `${name}.tsx`);
    if (!fs.existsSync(file)) continue;
    const spec = readSpec(kind, name);
    const typesFile = path.join('src', kind, name, 'types.ts');
    const id = `${kind}/${name}`;
    const key = digest([globalKey, fs.readFileSync(file, 'utf8'), fs.existsSync(typesFile) ? fs.readFileSync(typesFile, 'utf8') : '', spec ? JSON.stringify(spec) : ''].join('\n\u0000'));
    if (docgenCache[id]?.key === key) {
      props[id] = docgenCache[id].props;
      fromCache++;
      continue;
    }
    const fromFigma = figmaNames(spec);
    const docs = parser.parse(file);
    const doc = docs.find((d) => d.displayName === name) ?? docs[0];
    const defaults = sourceDefaults(fs.readFileSync(file, 'utf8'));
    props[`${kind}/${name}`] = {
      note: propsNote(kind, name),
      props: Object.values(doc?.props ?? {})
        .filter((p) => isOwn(p) || fromFigma.has(p.name))
        .sort((a, b) => Number(!isOwn(a)) - Number(!isOwn(b))) // the component's own props first, native ones after
        .map((p) => ({
          name: p.name,
          type: p.type.raw && p.type.raw.length < 120 ? p.type.raw : p.type.name,
          kind: p.type.name === 'enum' ? 'enum' : p.type.name,
          options: p.type.name === 'enum' ? orderOptions(((p.type.value ?? []) as { value: string }[]).map((v) => literal(v.value))) : undefined,
          required: p.required,
          defaultValue: p.defaultValue?.value ?? defaults[p.name],
          // A prop in both branches of a union gets both JSDoc lines from docgen: one line per branch.
          description: p.description ? p.description.split('\n').join(' / ') : isOwn(p) ? undefined : 'нативный атрибут элемента',
          native: isOwn(p) ? undefined : true,
        })),
      pseudo: [...new Set((spec?.props ?? []).filter((p) => p.role === 'state').flatMap((p) => Object.values(p.map ?? {}).map((r) => (r && typeof r === 'object' && 'pseudo' in r ? r.pseudo : undefined))).filter(Boolean))],
    };
    docgenCache[id] = { key, props: props[id] };
    parsed++;
  }
}
writeIfChanged('demo/.generated/props.json', `${JSON.stringify(props, null, 2)}\n`);
writeIfChanged(cacheFile, `${JSON.stringify(docgenCache, null, 2)}\n`);

console.log(`gen: ${components.length} component(s) exported, props for ${Object.keys(props).length} entity(ies) (docgen: ${parsed} разобрано, ${fromCache} из кэша)`);

// The shapes of spec.json gen reads (the full model is the server's mcp/src/types.ts).
type SpecLite = {
  props?: {
    react?: string | null;
    role?: string;
    map?: Record<string, { flag?: string; pseudo?: string } | string | boolean | null>;
  }[];
};
